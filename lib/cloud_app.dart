  Uint8List? photo;
  String mime = 'image/jpeg';
  bool busy = false;
  @override
  void initState() {
    super.initState();
    if (widget.donation) transactionMode = 'Quyên góp';
  }

  @override
  void dispose() {
    title.dispose();
    price.dispose();
    description.dispose();
    super.dispose();
  }

  Future<void> pick() async {
    try {
      final f = await ImagePicker().pickImage(
        source: ImageSource.gallery,
        maxWidth: 1600,
        imageQuality: 80,
      );
      if (f == null) return;
      final bytes = await f.readAsBytes();
      if (bytes.length > 5 * 1024 * 1024) {
        if (mounted) notice(context, 'Ảnh tối đa 5 MB.');
        return;
      }
      if (mounted) {
        setState(() {
          photo = bytes;
          mime =
              f.mimeType ??
              (f.name.toLowerCase().endsWith('.png')
                  ? 'image/png'
                  : 'image/jpeg');
        });
      }
    } catch (e) {
      if (mounted) notice(context, friendly(e));
    }
  }

  Future<void> submit() async {
    if (!form.currentState!.validate()) return;
    if (photo == null) {
      notice(context, 'Hãy thêm ảnh thật của món đồ.');
      return;
    }
    setState(() => busy = true);
    String? path;
    try {
      final uid = db.auth.currentUser!.id;
      path =
          '$uid/${DateTime.now().microsecondsSinceEpoch}.${mime == 'image/png'
              ? 'png'
              : mime == 'image/webp'
              ? 'webp'
              : 'jpg'}';
      await db.storage
          .from('listing-images')
          .uploadBinary(
            path,
            photo!,
            fileOptions: FileOptions(contentType: mime),
          );
      await db.from('listings').insert({
        'owner_id': uid,
        'title': title.text.trim(),
        'description': 'Tình trạng: $condition\n\n${description.text.trim()}',
        'price': transactionMode == 'Quyên góp' ? 0 : int.parse(price.text),
        'category': category,
        'area': widget.area,
        'image_path': path,
      });
      if (mounted) Navigator.pop(context);
    } catch (e) {
      if (path != null) {
        try {
          await db.storage.from('listing-images').remove([path]);
        } catch (_) {}
      }
      if (mounted) notice(context, friendly(e));
    } finally {
      if (mounted) setState(() => busy = false);
    }
  }

