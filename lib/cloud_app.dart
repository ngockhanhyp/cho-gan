class Chat extends StatefulWidget {
  final Map<String, dynamic> thread;
  final VoidCallback? onRead;
  const Chat({super.key, required this.thread, this.onRead});
  @override
  State<Chat> createState() => _Chat();
}

class _Chat extends State<Chat> {
  final input = TextEditingController();
  List<Map<String, dynamic>> messages = [];
  Timer? timer;
  bool sending = false, fetching = false;
  String? error;
  @override
  void initState() {
    super.initState();
    load();
    timer = Timer.periodic(const Duration(seconds: 3), (_) => load());
  }

  @override
  void dispose() {
    timer?.cancel();
    input.dispose();
    super.dispose();
  }

  Future<void> load() async {
    if (fetching) return;
    fetching = true;
    try {
      final rows = await db
          .from('messages')
          .select()
          .eq('conversation_id', widget.thread['id'])
          .order('created_at', ascending: false)
          .limit(100);
      if (mounted) {
        setState(() {
          messages = rows;
          error = null;
        });
        if (ModalRoute.of(context)?.isCurrent ?? false) {
          widget.onRead?.call();
        }
      }
    } catch (e) {
      if (mounted) setState(() => error = friendly(e));
    } finally {
      fetching = false;
    }
  }

  Future<void> send() async {
    final body = input.text.trim();
    if (sending || body.isEmpty || body.length > 2000) return;
    setState(() => sending = true);
    try {
      await db.from('messages').insert({
        'conversation_id': widget.thread['id'],
        'sender_id': db.auth.currentUser!.id,
        'body': body,
      });
      if (!mounted) return;
      if (input.text.trim() == body) input.clear();
      await load();
    } catch (e) {
      if (mounted) notice(context, friendly(e));
    } finally {
      if (mounted) setState(() => sending = false);
    }
  }

  @override
  Widget build(BuildContext c) => Scaffold(
    appBar: AppBar(title: const Text('Trò chuyện')),
    body: Center(
      child: ConstrainedBox(
        constraints: const BoxConstraints(maxWidth: 820),
        child: Column(
          children: [
            Container(
              padding: const EdgeInsets.fromLTRB(16, 12, 16, 12),
              decoration: const BoxDecoration(
                border: Border(bottom: BorderSide(color: line)),
              ),
              child: Row(
                children: [
                  SizedBox(
                    width: 52,
                    height: 52,
                    child: ListingImage(
                      path: widget.thread['listings']?['image_path'] ?? '',
                      size: 52,
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(
                          widget.thread['listings']?['title'] ?? '',
                          maxLines: 1,
                          overflow: TextOverflow.ellipsis,
                          style: const TextStyle(fontWeight: FontWeight.w600),
                        ),
                        const SizedBox(height: 2),
                        Text(
                          money(widget.thread['listings']?['price'] ?? 0),
                          style: const TextStyle(fontWeight: FontWeight.w900),
                        ),
                      ],
                    ),
                  ),
                  OutlinedButton.icon(
                    style: OutlinedButton.styleFrom(
                      minimumSize: const Size(0, 40),
                      padding: const EdgeInsets.symmetric(horizontal: 14),
                    ),
                    onPressed: () => Navigator.push(
                      context,
                      MaterialPageRoute(
                        builder: (_) => MeetingPage(thread: widget.thread),
                      ),
                    ),
                    icon: const Icon(Icons.event_available_outlined, size: 18),
                    label: const Text('Hẹn gặp'),
                  ),
                ],
              ),
            ),
            if (error != null)
              Padding(
                padding: const EdgeInsets.all(8),
                child: Text(error!, style: const TextStyle(color: Color(0xFFC62828))),
              ),
            Expanded(
              child: messages.isEmpty
                  ? const Center(
                      child: Padding(
                        padding: EdgeInsets.all(32),
                        child: Text(
                          'Chào người bán, hỏi tình trạng món đồ và hẹn giờ gặp nhé.\n'
                          'Đừng chuyển khoản trước khi xem hàng.',
                          textAlign: TextAlign.center,
                          style: TextStyle(color: muted, height: 1.6),
                        ),
                      ),
                    )
                  : ListView(
                      reverse: true,
                      padding: const EdgeInsets.fromLTRB(16, 16, 16, 8),
                      children: messages.map((m) {
                        final me = m['sender_id'] == db.auth.currentUser?.id;
                        return Align(
                          alignment: me ? Alignment.centerRight : Alignment.centerLeft,
                          child: Column(
                            crossAxisAlignment:
                                me ? CrossAxisAlignment.end : CrossAxisAlignment.start,
                            children: [
                              Container(
                                constraints: const BoxConstraints(maxWidth: 460),
                                margin: const EdgeInsets.only(top: 10),
                                padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 10),
                                decoration: BoxDecoration(
                                  color: me ? brand : soft,
                                  borderRadius: BorderRadius.only(
                                    topLeft: const Radius.circular(18),
                                    topRight: const Radius.circular(18),
                                    bottomLeft: Radius.circular(me ? 18 : 4),
                                    bottomRight: Radius.circular(me ? 4 : 18),
                                  ),
                                ),
                                child: Text(
                                  m['body'] ?? '',
                                  style: TextStyle(
                                    color: me ? Colors.white : ink,
                                    fontSize: 15,
                                    height: 1.4,
                                  ),
                                ),
                              ),
                              Padding(
                                padding: const EdgeInsets.only(top: 3, left: 4, right: 4),
                                child: Text(
                                  timeAgo(m['created_at']),
                                  style: const TextStyle(color: muted, fontSize: 11),
                                ),
                              ),
                            ],
                          ),
                        );
                      }).toList(),
                    ),
            ),
            SafeArea(
              child: Container(
                padding: const EdgeInsets.fromLTRB(12, 8, 12, 12),
                decoration: const BoxDecoration(
                  border: Border(top: BorderSide(color: line)),
                ),
                child: Row(
                  children: [
                    Expanded(
                      child: TextField(
                        controller: input,
                        maxLength: 2000,
                        maxLines: 4,
                        minLines: 1,
                        onSubmitted: (_) => send(),
                        decoration: InputDecoration(
                          hintText: 'Nhắn người hàng xóm…',
                          counterText: '',
                          border: OutlineInputBorder(
                            borderRadius: BorderRadius.circular(24),
                            borderSide: BorderSide.none,
                          ),
                          enabledBorder: OutlineInputBorder(
                            borderRadius: BorderRadius.circular(24),
                            borderSide: BorderSide.none,
                          ),
                          focusedBorder: OutlineInputBorder(
                            borderRadius: BorderRadius.circular(24),
                            borderSide: const BorderSide(color: brand),
                          ),
                        ),
                      ),
                    ),
                    const SizedBox(width: 8),
                    Material(
                      color: brand,
                      shape: const CircleBorder(),
                      child: IconButton(
                        tooltip: 'Gửi',
                        onPressed: sending ? null : send,
                        icon: const Icon(Icons.send_rounded, color: Colors.white),
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ],
        ),
      ),
    ),
  );
}
