  void initState() {
    super.initState();
    refresh();
    inboxUpdates.start();
    WidgetsBinding.instance.addPostFrameCallback((_) => maybeIntroducePassy());
    if (widget.authMessage != null) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        if (mounted) notice(context, widget.authMessage!);
      });
    }
    loadPreferredPassyArea().then((saved) {
      if (mounted && !areaPickerOpened && saved != null) {
        setState(() => area = saved);
      }
    });
    auth = db.auth.onAuthStateChange.listen((state) {
      refresh();
      if (state.event == AuthChangeEvent.signedIn) {
        WidgetsBinding.instance.addPostFrameCallback((_) => maybeIntroducePassy());
      }
      if (state.event == AuthChangeEvent.passwordRecovery) {
        WidgetsBinding.instance.addPostFrameCallback((_) {
          if (!mounted) return;
          Navigator.of(context).push(
            MaterialPageRoute(builder: (_) => const PasswordRecoveryPage()),
          );
        });
      }
    }, onError: (Object error) {
      if (mounted) notice(context, socialAuthErrorMessage(error));
    });
  }

  @override
  void dispose() {
    auth?.cancel();
    inboxUpdates.dispose();
    super.dispose();
  }

  Future<void> refresh() async {
    try {
      final data = await db
          .from('listings')
          .select('*,profiles!owner_id(name)')
          .order('created_at', ascending: false)
          .limit(200);
      List<Map<String, dynamic>> t = [];
      Set<String> f = {};
      if (db.auth.currentUser != null) {
        final rows = await db.from('favorites').select('listing_id');
        f = rows.map((e) => e['listing_id'] as String).toSet();
        t = await db
            .from('conversations')
            .select('*,listings(title,price,image_path)')
            .order('created_at', ascending: false);
      }
      if (mounted) {
        setState(() {
          listings = data;
          threads = t
              .map(
                (row) => {
                  ...row,
                  'listings':
                      row['listings'] ??
                      {
                        'title': 'Tin không còn hiển thị',
                        'price': 0,
                        'image_path': '',
                      },
                },
              )
              .toList();
          favorites = f;
          loading = false;
          error = null;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          error = friendly(e);
          loading = false;
        });
      }
    }
  }

  Future<bool> login() async {
    if (db.auth.currentUser != null) return true;
    await Navigator.push(
      context,
      MaterialPageRoute(builder: (_) => const Login()),
    );
    return db.auth.currentUser != null;
  }

  Future<void> favorite(Map<String, dynamic> x) async {
    if (!await login()) return;
    try {
      if (favorites.contains(x['id'])) {
        await db
            .from('favorites')
            .delete()
            .eq('user_id', db.auth.currentUser!.id)
            .eq('listing_id', x['id']);
      } else {
        await db.from('favorites').insert({
          'user_id': db.auth.currentUser!.id,
          'listing_id': x['id'],
        });
      }
      await refresh();
    } catch (e) {
      if (mounted) notice(context, friendly(e));
    }
  }

